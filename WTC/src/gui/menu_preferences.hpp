// ### resets ImGui hashing to the unchanged source; translated text is display-only.
inline std::string widget_label(const char* source) {
    if(!source)return {};
    const std::string_view key(source);
    if(key.starts_with("##"))return source;
    const auto marker=key.find("##");
    const std::string visible(key.substr(0,marker));
    const char* translated=label(marker==std::string_view::npos?source:visible.c_str());
    if(key.find("###")!=std::string_view::npos)
        return std::string(translated)+std::string(key.substr(key.find("###")));
    return std::string(translated)+"###"+source;
}
