struct settings {
    bool advanced=false;
    int language=1; // 0 Spanish, 1 English (public release default); manual profile save only.
    bool filter_static_air=true;
    int g2a_key=0;
    std::set<std::string> favorites;
    bool operator==(const settings&) const = default;
};
inline settings current;
inline int valid_language(int value) { return value==0?0:1; }
inline bool valid_favorite(std::string_view name) {
    if(name.empty() || name.size()>96)return false;
    for(unsigned char c:name)if(c<32 || c==127)return false;
    return true;
}
inline void toggle_favorite(const std::string& name) {
    if(current.favorites.erase(name))return;
    if(valid_favorite(name) && current.favorites.size()<128)current.favorites.insert(name);
}
