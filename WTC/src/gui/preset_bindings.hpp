template<class T, size_t N>
constexpr bool complete_preset_bindings(const std::array<T,N>& table) {
    for(const auto& entry:table) if(entry.preset==nullptr || entry.runtime==nullptr) return false;
    return true;
}
static_assert(complete_preset_bindings(bool_bindings));
static_assert(complete_preset_bindings(float_bindings));
static_assert(complete_preset_bindings(color_bindings));
static_assert(complete_preset_bindings(int_bindings));
